const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawn } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const readJSON = file => JSON.parse(fs.readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));

(async () => {
  const tools = readJSON(path.join(root, 'outputs/android-tools.json'));
  const identity = readJSON(path.join(root, 'outputs/android/build-identity.json'));
  const locations = readJSON(path.join(root, 'outputs/signing-locations.json'));
  const signing = readJSON(path.join(locations.SigningDirectory, 'signing-info.json'));
  const project = path.normalize(identity.projectDirectory);
  require('./patch-android-project.cjs')(project);
  const twa = readJSON(path.join(project, 'twa-manifest.json'));
  if (twa.packageId !== identity.packageId) throw new Error('The Android package differs from the saved identity.');
  identity.version = twa.appVersion;
  identity.versionCode = twa.appVersionCode;
  const env = { ...process.env, JAVA_HOME: tools.JdkDirectory, ANDROID_HOME: tools.SdkDirectory, ANDROID_SDK_ROOT: tools.SdkDirectory, PASESEGURO_KEYSTORE_PASSWORD: signing.keystorePassword, PASESEGURO_KEY_PASSWORD: signing.keyPassword };
  const pathKey = Object.keys(env).find(key => key.toLowerCase() === 'path') || 'Path';
  env[pathKey] = path.join(tools.JdkDirectory, 'bin') + ';' + env[pathKey];
  const run = (command, args, capture = false) => new Promise((resolve, reject) => {
    const child = spawn(command, args, { cwd: project, env, windowsHide: true });
    let output = '';
    child.stdout.on('data', chunk => { output += chunk; if (!capture) process.stdout.write(chunk); });
    child.stderr.on('data', chunk => { output += chunk; if (!capture) process.stderr.write(chunk); });
    child.on('error', reject);
    child.on('exit', code => code === 0 ? resolve(output) : reject(new Error(path.basename(command) + ' failed (' + code + '):\n' + output)));
    child.stdin.end();
  });
  await run(process.env.ComSpec || 'cmd.exe', ['/d', '/c', 'gradlew.bat', 'assembleRelease', 'bundleRelease', '--no-daemon', '--console=plain']);
  const buildTools = path.join(tools.SdkDirectory, 'build-tools/35.0.0');
  const unsigned = path.join(project, 'app/build/outputs/apk/release/app-release-unsigned.apk');
  const aligned = path.join(project, 'app-release-aligned.apk');
  const signed = path.join(project, 'app-release-signed.apk');
  await run(path.join(buildTools, 'zipalign.exe'), ['-P', '16', '-f', '4', unsigned, aligned]);
  const java = path.join(tools.JdkDirectory, 'bin/java.exe');
  const apkSigner = path.join(buildTools, 'lib/apksigner.jar');
  await run(java, ['-jar', apkSigner, 'sign', '--ks', signing.keystorePath, '--ks-key-alias', signing.alias, '--ks-pass', 'env:PASESEGURO_KEYSTORE_PASSWORD', '--key-pass', 'env:PASESEGURO_KEY_PASSWORD', '--out', signed, aligned]);
  const verification = await run(java, ['-jar', apkSigner, 'verify', '--verbose', '--print-certs', signed], true);
  const expected = identity.fingerprint.replace(/:/g, '').toLowerCase();
  if (!verification.toLowerCase().includes('certificate sha-256 digest: ' + expected)) throw new Error('APK certificate does not match the saved signing key.');
  await run(path.join(buildTools, 'zipalign.exe'), ['-c', '-P', '16', '4', signed]);
  const aapt = fs.existsSync(path.join(buildTools, 'aapt.exe')) ? 'aapt.exe' : 'aapt2.exe';
  const badging = await run(path.join(buildTools, aapt), ['dump', 'badging', signed], true);
  if (!badging.includes(`package: name='${identity.packageId}'`)) throw new Error('Unexpected APK package name.');
  const output = path.join(root, 'outputs/android');
  const file = path.join(output, `PaseSeguro-${identity.version}.apk`);
  fs.copyFileSync(signed, file);
  fs.writeFileSync(path.join(output, 'signature-verification.txt'), verification);
  fs.writeFileSync(path.join(output, 'apk-details.txt'), badging);
  const report = { apk: file, packageId: identity.packageId, version: identity.version, versionCode: identity.versionCode, bytes: fs.statSync(file).size, apkSha256: crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex'), certificateSha256: identity.fingerprint, signatureVerified: true, zipAlignmentVerified: true, minimumAndroidApi: badging.match(/sdkVersion:'(\d+)'/)?.[1], targetAndroidApi: badging.match(/targetSdkVersion:'(\d+)'/)?.[1] };
  const bundle = path.join(project, 'app/build/outputs/bundle/release/app-release.aab');
  const bundleOutput = path.join(output, `PaseSeguro-${identity.version}.aab`);
  fs.copyFileSync(bundle, bundleOutput);
  await run(path.join(tools.JdkDirectory, 'bin/jarsigner.exe'), ['-keystore', signing.keystorePath, '-storepass:env', 'PASESEGURO_KEYSTORE_PASSWORD', '-keypass:env', 'PASESEGURO_KEY_PASSWORD', bundleOutput, signing.alias], true);
  const bundleVerification = await run(path.join(tools.JdkDirectory, 'bin/jarsigner.exe'), ['-verify', bundleOutput], true);
  if (!bundleVerification.includes('jar verified')) throw new Error('AAB signature verification failed');
  report.aab = bundleOutput;
  report.aabSha256 = crypto.createHash('sha256').update(fs.readFileSync(bundleOutput)).digest('hex');
  report.aabSignatureVerified = true;
  fs.writeFileSync(path.join(output, 'build-report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; });
